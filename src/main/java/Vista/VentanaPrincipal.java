    public void registarNuevoElectronico(int codigo, String nombre, double precioBase, String marca, String tGarantia) {
        
        ModeloElectronico nuevoElec = new ModeloElectronico(codigo, nombre, precioBase, marca, tGarantia);
        modelo.agregarElectronico(nuevoElec);
        javax.swing.JOptionPane.showMessageDialog(this, "Registrado Con exito");
    }
    
    public void registarNuevoAlimento(int codigo, String nombre, double precioBase, String fechaVencimiento, double pesoNeto) {
        
        ModeloAlimento nuevoAlim = new ModeloAlimento(codigo, nombre, precioBase, fechaVencimiento, pesoNeto);
        modelo.agregarAlimentos(nuevoAlim);
        javax.swing.JOptionPane.showMessageDialog(this, "Registrado Con exito");
    }
    
    public void registarNuevoBelleza(int codigo, String nombre, int precioBase, double volumen, String tipoPiel) {
        
        ModeloBelleza nuevoBell = new ModeloBelleza(codigo, nombre, precioBase, volumen, tipoPiel);
        modelo.agregarBellezas(nuevoBell);
        javax.swing.JOptionPane.showMessageDialog(this, "Registrado Con exito");
    }
    
    
    

